CREATE TABLE [dbo].[FactSales](
    [SalesKey] [bigint] IDENTITY(1,1) NOT NULL,
    [OrderDateKey] [int] NOT NULL,
    [RequiredDateKey] [int] NOT NULL,
    [ShippedDateKey] [int] NOT NULL,
    [CustomerKey] [int] NOT NULL,
    [ProductKey] [int] NOT NULL,
    [EmployeeKey] [int] NOT NULL,
    [ShipperKey] [int] NOT NULL,
    [ShipLocationKey] [int] NOT NULL,
    [OrderID] [int] NOT NULL,
    [UnitPrice] [decimal](18, 2) NOT NULL,
    [Quantity] [smallint] NOT NULL,
    [Discount] [decimal](5, 4) NOT NULL CONSTRAINT [DF_FactSales_Discount] DEFAULT ((0)),
    [AllocatedFreight] [decimal](18, 2) NOT NULL CONSTRAINT [DF_FactSales_AllocatedFreight] DEFAULT ((0)),
    [GrossAmount] AS (CONVERT([decimal](18,2), [UnitPrice] * [Quantity])) PERSISTED,
    [DiscountAmount] AS (CONVERT([decimal](18,2), ([UnitPrice] * [Quantity]) * [Discount])) PERSISTED,
    [NetSales] AS (CONVERT([decimal](18,2), ([UnitPrice] * [Quantity]) * ((1) - [Discount]))) PERSISTED,
    [DaysToShip] [int] NULL,
    [DaysLate] [int] NULL,
    [LoadDate] [datetime] NOT NULL CONSTRAINT [DF_FactSales_LoadDate] DEFAULT (getdate()),
    CONSTRAINT [PK_FactSales] PRIMARY KEY CLUSTERED ([SalesKey] ASC),
    CONSTRAINT [UQ_FactSales_Line] UNIQUE NONCLUSTERED ([OrderID] ASC, [ProductKey] ASC),
    CONSTRAINT [FK_FactSales_Customer] FOREIGN KEY ([CustomerKey]) REFERENCES [dbo].[DimCustomer] ([CustomerKey]),
    CONSTRAINT [FK_FactSales_Employee] FOREIGN KEY ([EmployeeKey]) REFERENCES [dbo].[DimEmployee] ([EmployeeKey]),
    CONSTRAINT [FK_FactSales_OrderDate] FOREIGN KEY ([OrderDateKey]) REFERENCES [dbo].[DimDate] ([DateKey]),
    CONSTRAINT [FK_FactSales_Product] FOREIGN KEY ([ProductKey]) REFERENCES [dbo].[DimProduct] ([ProductKey]),
    CONSTRAINT [FK_FactSales_RequiredDate] FOREIGN KEY ([RequiredDateKey]) REFERENCES [dbo].[DimDate] ([DateKey]),
    CONSTRAINT [FK_FactSales_ShipLocation] FOREIGN KEY ([ShipLocationKey]) REFERENCES [dbo].[DimShipLocation] ([ShipLocationKey]),
    CONSTRAINT [FK_FactSales_ShippedDate] FOREIGN KEY ([ShippedDateKey]) REFERENCES [dbo].[DimDate] ([DateKey]),
    CONSTRAINT [FK_FactSales_Shipper] FOREIGN KEY ([ShipperKey]) REFERENCES [dbo].[DimShipper] ([ShipperKey]),
    CONSTRAINT [CK_FactSales_Discount] CHECK ([Discount] >= (0) AND [Discount] <= (1)),
    CONSTRAINT [CK_FactSales_Freight] CHECK ([AllocatedFreight] >= (0)),
    CONSTRAINT [CK_FactSales_Price] CHECK ([UnitPrice] >= (0)),
    CONSTRAINT [CK_FactSales_Quantity] CHECK ([Quantity] > (0))
);